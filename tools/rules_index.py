"""Build 06-rules-index.md from the four guides, and cross-check rule ids.

    python3 tools/rules_index.py [--check]

Collects every rule written as `**B-12 . REQUIRED** - text` (the separator is a middle dot), writes the index with
counts, and stops with an error when a rule id is duplicated, when a level in the checker script disagrees with the
guide, or when a text refers to a rule id that does not exist. `--check` only checks.
"""
import os
import re
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
GUIDES = [("01-builders-and-architects-guide.md", "1 Builder's and Architect's"),
          ("02-interior-decorators-guide.md", "2 Interior Decorator's"),
          ("03-furniture-and-fixtures-guide.md", "3 Furniture and Fixtures"),
          ("04-delivery-and-acceptance-guide.md", "4 Delivery and Acceptance")]
RULE = re.compile(r"^\*\*([BDFX]-\d+[a-z]?) \u00b7 (REQUIRED|RECOMMENDED)(?: \u00b7 ([A-Za-z]+))?\*\* - (.*)$")
REF = re.compile(r"\b([BDFX]-\d+[a-z]?)\b")


def collect():
    """Parse the guides. Returns (rules dict, order list, problems list). Each rule has level, guide, text (first sentence)
    and statement (the whole paragraph)."""
    rules, order, text_all = {}, [], {}
    for fn, label in GUIDES:
        with open(os.path.join(ROOT, fn), encoding="utf-8") as fh:
            lines = fh.read().split("\n")
        text_all[fn] = "\n".join(lines)
        i = 0
        while i < len(lines):
            m = RULE.match(lines[i])
            if m:
                body = m.group(4)
                j = i + 1
                while j < len(lines) and lines[j].strip() and not lines[j].startswith(("|", "```", "**", "#", "-", "*")):
                    body += " " + lines[j].strip()
                    j += 1
                rid = m.group(1)
                if rid in rules:
                    sys.exit("duplicate rule id " + rid)
                first = re.split(r"(?<=[.!?])\s", body, maxsplit=1)[0]
                rules[rid] = {"level": m.group(2), "guide": label, "file": fn, "text": first.replace("|", "/"), "statement": first, "paragraph": body, "extension": m.group(3)}
                order.append(rid)
                i = j
            else:
                i += 1
    return rules, order


def cross_check(rules):
    problems = []
    allfiles = [fn for fn, _ in GUIDES] + ["05-worked-example.md", "README.md"]
    for fn in allfiles:
        with open(os.path.join(ROOT, fn), encoding="utf-8") as fh:
            for rid in REF.findall(fh.read()):
                if rid not in rules:
                    problems.append("%s refers to %s, which does not exist" % (fn, rid))
    for fn in os.listdir(os.path.join(ROOT, "tools")):
        if fn.endswith(".py"):
            with open(os.path.join(ROOT, "tools", fn), encoding="utf-8") as fh:
                for rid in set(REF.findall(fh.read())):
                    if rid not in rules:
                        problems.append("tools/%s refers to %s, which does not exist" % (fn, rid))
    return sorted(set(problems))


def render(rules, order):
    req = sum(1 for r in rules.values() if r["level"] == "REQUIRED")
    rec = len(rules) - req
    out = ["# Rules index", "",
           "Every rule of the four guides in one table. Generated by `tools/rules_index.py`; do not edit by hand.", "",
           "The same rules, with machine fields, are in `rules.json`.", "",
           "**%d rules: %d REQUIRED and %d RECOMMENDED.**" % (len(rules), req, rec), "",
           "| Guide | REQUIRED | RECOMMENDED | Total |", "|---|---:|---:|---:|"]
    for _, label in GUIDES:
        a = sum(1 for r in rules.values() if r["guide"] == label and r["level"] == "REQUIRED")
        b = sum(1 for r in rules.values() if r["guide"] == label and r["level"] == "RECOMMENDED")
        out.append("| %s | %d | %d | %d |" % (label, a, b, a + b))
    out += ["| **All** | **%d** | **%d** | **%d** |" % (req, rec, len(rules)), "",
            "| Rule | Level | Guide | Statement |", "|---|---|---|---|"]
    for rid in order:
        r = rules[rid]
        out.append("| %s | %s | %s | %s |" % (rid, r["level"], r["guide"].split(" ")[0], r["text"]))
    return "\n".join(out) + "\n"


def main():
    rules, order = collect()
    problems = cross_check(rules)
    if problems:
        sys.exit("\n".join(problems))
    req = sum(1 for r in rules.values() if r["level"] == "REQUIRED")
    rec = len(rules) - req
    if "--check" in sys.argv:
        print("rules: %d (%d REQUIRED, %d RECOMMENDED); cross-checks passed" % (len(rules), req, rec))
        return
    with open(os.path.join(ROOT, "06-rules-index.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(rules, order))
    print("wrote 06-rules-index.md: %d rules (%d REQUIRED, %d RECOMMENDED)" % (len(rules), req, rec))


if __name__ == "__main__":
    main()
