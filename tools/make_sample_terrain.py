"""Write a trivial synthetic terrain patch (a plane or a slope) and its sidecar, for tests and examples only.

    python3 make_sample_terrain.py OUT_DIR --request site-request.json
                                   [--height-at-origin H] [--slope-x SX] [--slope-y SY] [--pixel-size 0.5]

Real terrain comes from the terrain source, not from this script. The plane or slope covers the patch bounds of the request;
its height at the building origin is --height-at-origin (default: the request's finished floor elevation, which gives a flat pad),
rising SX per metre east and SY per metre north. Writes OUT_DIR/terrain/patch.tif and OUT_DIR/terrain/patch.json
(schemas/terrain-patch.schema.json). The output is deterministic.

Requires: pip install numpy pillow
"""
import argparse
import hashlib
import json
import math
import os

import numpy as np

from terrain_lib import sample_grid, sha256_file, write_patch

CRS_NAME = "SYNTHETIC-SITE"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("out_dir")
    ap.add_argument("--request", required=True)
    ap.add_argument("--height-at-origin", type=float, default=None)
    ap.add_argument("--slope-x", type=float, default=0.0)
    ap.add_argument("--slope-y", type=float, default=0.0)
    ap.add_argument("--pixel-size", type=float, default=0.5)
    a = ap.parse_args()
    with open(a.request, encoding="utf-8") as fh:
        req = json.load(fh)
    e0, n0 = req["buildingOrigin"]["x"], req["buildingOrigin"]["y"]
    h0 = req["finishedFloorElevationMetres"] if a.height_at_origin is None else a.height_at_origin
    (x0, y0), (x1, y1) = req["patch"]["bounds"]["min"], req["patch"]["bounds"]["max"]
    ps = a.pixel_size
    x0, y0, x1, y1 = x0 - ps, y0 - ps, x1 + ps, y1 + ps          # the patch rectangle runs between sample centres: pad one pixel
    w, h = int(math.ceil((x1 - x0) / ps)), int(math.ceil((y1 - y0) / ps))
    origin = (x0, y0 + h * ps)                                   # outer north-west corner
    X, Y = sample_grid(np.zeros((h, w)), origin, ps)
    z = h0 + a.slope_x * (X - e0) + a.slope_y * (Y - n0)
    out = os.path.join(a.out_dir, "terrain")
    os.makedirs(out, exist_ok=True)
    tif = os.path.join(out, "patch.tif")
    write_patch(tif, z, origin, ps)
    params = json.dumps({"h0": h0, "sx": a.slope_x, "sy": a.slope_y, "ps": ps, "bounds": req["patch"]["bounds"]}, sort_keys=True)
    side = {
        "format": "terrain-patch/1",
        "package": {"name": "synthetic-test-ground", "version": "0.0.0", "sha256": hashlib.sha256(params.encode()).hexdigest()},
        "patch": {"file": "patch.tif", "sha256": sha256_file(tif), "level": 0, "pixelSizeMetres": ps, "width": w, "height": h,
                  "origin": {"x": origin[0], "y": origin[1]}},
        "crs": {"name": CRS_NAME, "definition": "synthetic test ground with no real projection: x east, y north, metres"},
        "frame": req["frame"],
        "verticalDatum": {"name": "mean sea level", "seaLevelMetres": 0.0},
        "water": {"distanceToShoreMetres": None},
        "licence": {"statement": "CC0-1.0: synthetic test data, no restrictions", "source": "generated by tools/make_sample_terrain.py"},
    }
    with open(os.path.join(out, "patch.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(side, fh, indent=2)
        fh.write("\n")
    print("wrote %s: %d x %d samples at %g m, height %.3f m at the origin, slope %g east %g north" % (
        tif, w, h, ps, h0, a.slope_x, a.slope_y))


if __name__ == "__main__":
    main()
